/// An sRGB colour and its alpha, each from 0 to 1.
#[derive(Clone, Copy)]
struct Rgba {
    red: f64,
    green: f64,
    blue: f64,
    alpha: f64,
}

impl Rgba {
    fn new((red, green, blue, alpha): (f64, f64, f64, f64)) -> PyResult<Self> {
        if ![red, green, blue, alpha]
            .iter()
            .all(|value| value.is_finite() && (0.0..=1.0).contains(value))
        {
            return Err(PdfError::new_err(
                "colour components and alpha must be numbers from 0 to 1",
            ));
        }
        Ok(Self {
            red,
            green,
            blue,
            alpha,
        })
    }

    fn device(self) -> DeviceColor {
        DeviceColor::Rgb(self.red, self.green, self.blue)
    }

    fn opacity(self) -> NormalizedF32 {
        NormalizedF32::new(self.alpha as f32).unwrap_or(NormalizedF32::ONE)
    }

    /// The alpha as an ExtGState entry, when it is below 1.
    fn translucent(self) -> Option<f64> {
        (self.alpha < 1.0).then_some(self.alpha)
    }

    fn krilla_fill(self, even_odd: bool) -> Fill {
        Fill {
            paint: generate::device_paint(self.device()),
            opacity: self.opacity(),
            rule: if even_odd {
                FillRule::EvenOdd
            } else {
                FillRule::NonZero
            },
        }
    }
}

/// How a path or text is stroked.
struct StrokeStyle {
    color: Rgba,
    width: f64,
    cap: u8,
    join: u8,
    miter_limit: f64,
    dashes: Vec<f64>,
    dash_offset: f64,
}

/// A stroke's colour, width, cap, join, miter limit, dash lengths, and dash
/// offset, as Python passes them.
type StrokeArgs = ((f64, f64, f64, f64), f64, u8, u8, f64, Vec<f64>, f64);

impl StrokeStyle {
    fn new(
        (color, width, cap, join, miter_limit, dashes, dash_offset): StrokeArgs,
    ) -> PyResult<Self> {
        if !(width.is_finite() && width > 0.0 && width <= f64::from(f32::MAX)) {
            return Err(PdfError::new_err("stroke width must be a positive number"));
        }
        if cap > 2 || join > 2 {
            return Err(PdfError::new_err("unknown line cap or line join"));
        }
        if !(miter_limit.is_finite() && (1.0..=f64::from(f32::MAX)).contains(&miter_limit)) {
            return Err(PdfError::new_err(
                "miter_limit must be a number of at least 1",
            ));
        }
        if !dashes
            .iter()
            .all(|value| value.is_finite() && (0.0..=f64::from(f32::MAX)).contains(value))
            || (!dashes.is_empty() && dashes.iter().all(|value| *value == 0.0))
        {
            return Err(PdfError::new_err(
                "dash lengths must be non-negative numbers, not all zero",
            ));
        }
        coordinate(dash_offset)?;
        Ok(Self {
            color: Rgba::new(color)?,
            width,
            cap,
            join,
            miter_limit,
            dashes,
            dash_offset,
        })
    }

    /// Append the operators that select this stroke after a `q`; the
    /// initial values are left out.
    fn write_ops(&self, out: &mut String) {
        out.push_str(&format!(
            "{} {} {} RG\n",
            draw::fmt(self.color.red),
            draw::fmt(self.color.green),
            draw::fmt(self.color.blue)
        ));
        if self.width != 1.0 {
            out.push_str(&format!("{} w\n", draw::fmt(self.width)));
        }
        if self.cap != 0 {
            out.push_str(&format!("{} J\n", self.cap));
        }
        if self.join != 0 {
            out.push_str(&format!("{} j\n", self.join));
        }
        if self.miter_limit != 10.0 {
            out.push_str(&format!("{} M\n", draw::fmt(self.miter_limit)));
        }
        if !self.dashes.is_empty() {
            let lengths: Vec<String> = self.dashes.iter().map(|value| draw::fmt(*value)).collect();
            out.push_str(&format!(
                "[{}] {} d\n",
                lengths.join(" "),
                draw::fmt(self.dash_offset)
            ));
        }
    }

    fn krilla(&self) -> Stroke {
        Stroke {
            paint: generate::device_paint(self.color.device()),
            width: self.width as f32,
            miter_limit: self.miter_limit as f32,
            line_cap: match self.cap {
                1 => LineCap::Round,
                2 => LineCap::Square,
                _ => LineCap::Butt,
            },
            line_join: match self.join {
                1 => LineJoin::Round,
                2 => LineJoin::Bevel,
                _ => LineJoin::Miter,
            },
            opacity: self.color.opacity(),
            dash: (!self.dashes.is_empty()).then(|| StrokeDash {
                array: self.dashes.iter().map(|value| *value as f32).collect(),
                offset: self.dash_offset as f32,
            }),
        }
    }
}

/// ExtGState entries that a piece sets; `None` leaves an entry as it is, so
/// an alpha inside a blend scope keeps the scope's blend mode.
#[derive(Clone, Copy, PartialEq)]
pub(crate) struct GraphicsState {
    fill_alpha: Option<f64>,
    stroke_alpha: Option<f64>,
    blend: Option<u8>,
    /// The soft mask's group, by index into `Composed::groups`, and what
    /// it reads from the group.
    mask: Option<(usize, SoftMaskKind)>,
}

impl GraphicsState {
    /// The ExtGState dictionary; `groups` holds the object of each group
    /// Form, which a soft mask names.
    pub(crate) fn dictionary(self, groups: &[lopdf::ObjectId]) -> lopdf::Dictionary {
        let mut dict = lopdf::Dictionary::new();
        if let Some((group, kind)) = self.mask {
            let subtype: &[u8] = match kind {
                SoftMaskKind::Alpha => b"Alpha",
                SoftMaskKind::Luminosity => b"Luminosity",
            };
            let mut mask = lopdf::Dictionary::new();
            mask.set("Type", lopdf::Object::Name(b"Mask".to_vec()));
            mask.set("S", lopdf::Object::Name(subtype.to_vec()));
            mask.set("G", lopdf::Object::Reference(groups[group]));
            dict.set("SMask", mask);
        }
        dict.set("Type", lopdf::Object::Name(b"ExtGState".to_vec()));
        if let Some(alpha) = self.fill_alpha {
            dict.set("ca", lopdf::Object::Real(alpha as f32));
        }
        if let Some(alpha) = self.stroke_alpha {
            dict.set("CA", lopdf::Object::Real(alpha as f32));
        }
        if let Some(mode) = self.blend {
            dict.set(
                "BM",
                lopdf::Object::Name(BLEND_MODES[usize::from(mode)].as_bytes().to_vec()),
            );
        }
        dict
    }

    fn is_empty(self) -> bool {
        self.fill_alpha.is_none()
            && self.stroke_alpha.is_none()
            && self.blend.is_none()
            && self.mask.is_none()
    }
}

/// The geometry of a path or clip in display space: one byte per operator,
/// `m` and `l` with two coordinates, `c` with six, and `h` with none.
struct PathData {
    operators: Vec<u8>,
    coordinates: Vec<f64>,
}

impl PathData {
    /// Check the operators against the coordinates and return the path with
    /// its point count.
    fn new(operators: &str, coordinates: Vec<f64>) -> PyResult<(Self, usize)> {
        if !operators.starts_with('m') {
            return Err(PdfError::new_err("a path starts with a move"));
        }
        let mut expected = 0usize;
        for operator in operators.bytes() {
            expected += match operator {
                b'm' | b'l' => 2,
                b'c' => 6,
                b'h' => 0,
                _ => {
                    return Err(PdfError::new_err(format!(
                        "unknown path operator {:?}",
                        char::from(operator)
                    )));
                }
            };
        }
        if expected != coordinates.len() {
            return Err(PdfError::new_err(
                "path operators and coordinates do not match",
            ));
        }
        for value in &coordinates {
            coordinate(*value)?;
        }
        Ok((
            Self {
                operators: operators.as_bytes().to_vec(),
                coordinates,
            },
            expected / 2,
        ))
    }

    /// Call `segment` with each operator and its coordinates.
    fn segments(&self, mut segment: impl FnMut(u8, &[f64])) {
        let mut offset = 0;
        for &operator in &self.operators {
            let count = match operator {
                b'm' | b'l' => 2,
                b'c' => 6,
                _ => 0,
            };
            segment(operator, &self.coordinates[offset..offset + count]);
            offset += count;
        }
    }

    fn write_ops(&self, out: &mut String) {
        self.segments(|operator, values| {
            for value in values {
                out.push_str(&draw::fmt(*value));
                out.push(' ');
            }
            out.push(char::from(operator));
            out.push('\n');
        });
    }

    fn krilla(&self) -> Option<KrillaPath> {
        let mut builder = PathBuilder::new();
        self.segments(|operator, values| {
            let v: Vec<f32> = values.iter().map(|value| *value as f32).collect();
            match operator {
                b'm' => builder.move_to(v[0], v[1]),
                b'l' => builder.line_to(v[0], v[1]),
                b'c' => builder.cubic_to(v[0], v[1], v[2], v[3], v[4], v[5]),
                _ => builder.close(),
            }
        });
        builder.finish()
    }
}

/// A tag scope: a structure element of a tagged new document.
struct TagSpec {
    /// The index of the role in `TAG_ROLES`.
    role: usize,
    alt: Option<String>,
    lang: Option<String>,
    title: Option<String>,
    actual_text: Option<String>,
    /// What a table header cell heads, for `TH`.
    scope: TableHeaderScope,
    /// How a list numbers its items, for `L`.
    numbering: ListNumbering,
}

/// The table header scopes, by their PDF names.
const TABLE_HEADER_SCOPES: [(&str, TableHeaderScope); 3] = [
    ("Row", TableHeaderScope::Row),
    ("Column", TableHeaderScope::Column),
    ("Both", TableHeaderScope::Both),
];

/// The list numbering styles, by their PDF names.
const LIST_NUMBERINGS: [(&str, ListNumbering); 9] = [
    ("None", ListNumbering::None),
    ("Disc", ListNumbering::Disc),
    ("Circle", ListNumbering::Circle),
    ("Square", ListNumbering::Square),
    ("Decimal", ListNumbering::Decimal),
    ("LowerRoman", ListNumbering::LowerRoman),
    ("UpperRoman", ListNumbering::UpperRoman),
    ("LowerAlpha", ListNumbering::LowerAlpha),
    ("UpperAlpha", ListNumbering::UpperAlpha),
];

impl TagSpec {
    fn is_artifact(&self) -> bool {
        TAG_ROLES[self.role] == "Artifact"
    }

    fn kind(&self) -> TagKind {
        macro_rules! with_attributes {
            ($tag:expr) => {
                $tag.with_lang(self.lang.clone())
                    .with_alt_text(self.alt.clone())
                    .with_actual_text(self.actual_text.clone())
                    .into()
            };
        }
        let heading = |level: u16| {
            let level = NonZeroU16::new(level).unwrap_or(NonZeroU16::MIN);
            with_attributes!(Tag::Hn(level, self.title.clone()))
        };
        match TAG_ROLES[self.role] {
            "Part" => with_attributes!(Tag::Part),
            "Art" => with_attributes!(Tag::Article),
            "Sect" => with_attributes!(Tag::Section),
            "BlockQuote" => with_attributes!(Tag::BlockQuote),
            "Caption" => with_attributes!(Tag::Caption),
            "TOC" => with_attributes!(Tag::TOC),
            "TOCI" => with_attributes!(Tag::TOCI),
            "Index" => with_attributes!(Tag::Index),
            "NonStruct" => with_attributes!(Tag::NonStruct),
            "P" => with_attributes!(Tag::P),
            "H1" => heading(1),
            "H2" => heading(2),
            "H3" => heading(3),
            "H4" => heading(4),
            "H5" => heading(5),
            "H6" => heading(6),
            "L" => with_attributes!(Tag::L(self.numbering)),
            "LI" => with_attributes!(Tag::LI),
            "Lbl" => with_attributes!(Tag::Lbl),
            "LBody" => with_attributes!(Tag::LBody),
            "Table" => with_attributes!(Tag::Table),
            "TR" => with_attributes!(Tag::TR),
            "TH" => with_attributes!(Tag::TH(self.scope)),
            "TD" => with_attributes!(Tag::TD),
            "THead" => with_attributes!(Tag::THead),
            "TBody" => with_attributes!(Tag::TBody),
            "TFoot" => with_attributes!(Tag::TFoot),
            "Span" => with_attributes!(Tag::Span),
            "Quote" => with_attributes!(Tag::InlineQuote),
            "Note" => with_attributes!(Tag::Note),
            "Reference" => with_attributes!(Tag::Reference),
            "BibEntry" => with_attributes!(Tag::BibEntry),
            "Code" => with_attributes!(Tag::Code),
            "Figure" => with_attributes!(Tag::Figure(self.alt.clone())),
            "Formula" => with_attributes!(Tag::Formula(self.alt.clone())),
            _ => with_attributes!(Tag::Div),
        }
    }
}

