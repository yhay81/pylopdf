/// An image that the canvas draws, once however often it is placed.
pub(crate) enum CanvasImage {
    /// For a page of an open document: the input, kept unparsed while the
    /// document had placed it, or the parsed image.
    Lopdf {
        digest: ImageDigest,
        input: Option<ImageInput>,
        parts: Option<ImageParts>,
    },
    /// For a page of a new document: the image that krilla embeds.
    Krilla {
        image: KrillaImage,
        width: u32,
        height: u32,
    },
}

impl CanvasImage {
    pub(crate) fn digest(&self) -> Option<&ImageDigest> {
        match self {
            Self::Lopdf { digest, .. } => Some(digest),
            Self::Krilla { .. } => None,
        }
    }

    /// Return the parsed image, parsing input that was kept unparsed.
    pub(crate) fn take_parts(&mut self) -> PyResult<ImageParts> {
        let Self::Lopdf { input, parts, .. } = self else {
            return Err(PdfError::new_err("a new document's image has no parts"));
        };
        if let Some(parts) = parts.take() {
            return Ok(parts);
        }
        match input.take() {
            Some(input) => input.parse(),
            None => Err(PdfError::new_err("a canvas image was already placed")),
        }
    }
}

