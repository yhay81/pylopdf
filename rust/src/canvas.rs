//! Canvas: drawing recorded in paint order for one page.
//!
//! A canvas records structured drawing operations: paths, text, images,
//! placed pages, and the scopes around them. Two backends consume a
//! recording.
//!
//! A canvas on a page of an open document (`Page.draw()`) is composed into
//! content operators in display space, the top-left-origin space with the
//! page rotation resolved, and placed as one Form XObject: one flip at the
//! start of the composed Form maps display space to the Form's PDF space.
//! Paths, clips, transforms, and blend modes are operators of their own, an
//! opacity scope becomes a transparency group Form drawn at that opacity, and
//! a mask scope selects an ExtGState whose soft mask is a group Form of the
//! operations recorded for the mask's own target.
//! Text in an embedded OpenType face is generated by krilla, one page for
//! each run of consecutive text items, and imported as a Form; Standard 14
//! text is written as text operators, images as Image XObjects, and placed
//! pages as imported Form XObjects, each through its placement matrix. Those
//! pieces describe PDF space, so each is wrapped in the flip again, which
//! returns to it.
//!
//! A canvas on a page of a new document (`pylopdf.create()`) is replayed
//! onto a krilla surface, which shares display space, so krilla writes the
//! whole document: its fonts, images, transparency groups, and, for tagged
//! documents, the structure tree that tag scopes describe.

