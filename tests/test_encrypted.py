"""Tests for reading encrypted PDFs.

Fixtures live under tests/assets/encrypted/ and are generated by generate.py.
Passwords are user="userpw" and owner="ownerpw"; owneronly-* uses an empty
user password.
"""

from __future__ import annotations

import io
from pathlib import Path
from typing import Literal

import pytest

import pylopdf

ASSETS = Path(__file__).parent / "assets" / "encrypted"

#: Every standard security handler revision, by the fixture that uses it.
HANDLERS = {
    "user-rc4-40.pdf": "Standard V1 R2 40-bit RC4",
    "user-rc4-128.pdf": "Standard V2 R3 128-bit RC4",
    "user-r4-rc4-128.pdf": "Standard V4 R4 128-bit RC4",
    "user-aes-128.pdf": "Standard V4 R4 128-bit AES",
    "user-aes-128-plain-metadata.pdf": "Standard V4 R4 128-bit AES",
    "user-aes-256-r5.pdf": "Standard V5 R5 256-bit AES",
    "user-aes-256.pdf": "Standard V5 R6 256-bit AES",
    "user-aes-256-object-streams.pdf": "Standard V5 R6 256-bit AES",
}
USER_PROTECTED = list(HANDLERS)
USER = pytest.mark.parametrize("name", USER_PROTECTED)


@USER
def test_open_without_password_raises_on_use(name: str) -> None:
    doc = pylopdf.open(ASSETS / name)
    assert doc.needs_password
    with pytest.raises(ValueError, match="encrypted"):
        _ = len(doc.pages)
    with pytest.raises(ValueError, match="encrypted"):
        doc.to_bytes()


@USER
def test_open_with_user_password(name: str) -> None:
    doc = pylopdf.open(ASSETS / name, password="userpw")
    assert len(doc.pages) == 2
    assert not doc.needs_password
    assert "Encrypted page one" in doc.pages[0].text()
    assert doc.pages[0].pixmap(matrix=pylopdf.Matrix(0.5, 0.5), alpha=True).to_bytes().startswith(b"\x89PNG")


@USER
def test_open_with_owner_password(name: str) -> None:
    """Derive the file key from the user password that the owner password recovers.

    lopdf 0.45 derived it from the owner password itself for revisions 2 to 4,
    so the content of the RC4 and AES-128 assets decrypted to nothing
    (J-F-Liu/lopdf#573).
    """
    doc = pylopdf.open(ASSETS / name, password="ownerpw")
    assert len(doc.pages) == 2
    assert "Encrypted page one" in doc.pages[0].text()


