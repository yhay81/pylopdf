"""Generate pylopdf's migration hints from the pymupdf capability map and the pylopdf 0.15 table.

``src/pylopdf/_migration_hints.py`` maps every pymupdf name that pylopdf does
not provide under that name to one English message: the replacement and the
map's hint for a replaced name, the roadmap milestone for a planned
capability, and the hint or the fact that pylopdf leaves it out for the rest.
It also maps every name of pylopdf 0.15.0's public API that the API reset
removed, from ``api/pylopdf-0.15.json`` or, for a pymupdf name, from the
capability map, and lists those names in ``PYLOPDF_015_REMOVED``, which the
codemod uses to keep pymupdf hints out of pylopdf programs, and the names
that only pylopdf 0.15 had in ``PYLOPDF_015_ONLY``, which it keeps out of
pymupdf programs. AttributeError
messages and ``python -m pylopdf.migrate`` read it. Run it after editing
``api/pymupdf-parity.json``, ``api/pylopdf-0.15.json``, or
``api/public-api.json``; ``--check`` reports stale output without writing it,
and every run fails when a removed 0.15 name has no hint or a replacement
names a symbol that is not public.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import cast

from check_parity import MILESTONES, public_symbols

ROOT = Path(__file__).resolve().parent.parent
MANIFEST_PATH = ROOT / "api" / "pymupdf-parity.json"
RELEASE_PATH = ROOT / "api" / "pylopdf-0.15.json"
PUBLIC_API_PATH = ROOT / "api" / "public-api.json"
HINTS_PATH = ROOT / "src" / "pylopdf" / "_migration_hints.py"

HEADER = '''"""Migration hints for pymupdf names and pylopdf 0.15 names that pylopdf does not provide.

Generated by ``tools/generate_migration_hints.py`` from
``api/pymupdf-parity.json`` and ``api/pylopdf-0.15.json``; do not edit by
hand. Keys are names: a module attribute, ``Class.member``, or a prefix
ending in ``*`` that covers a group of module constants.
"""

HINTS: dict[str, str] = {
'''


def _message(name: str, entry: dict[str, object]) -> str | None:
    """Return the hint message for one manifest entry, or None when pylopdf provides the name."""
    status = entry["status"]
    relation = entry["relation"]
    target = entry["pylopdf"]
    milestone = entry["milestone"]
    hint = entry.get("hint")
    suffix = f" {hint}" if hint else ""
    if status == "available":
        if relation == "same" and target == name:
            return None
        return f"{name} is {target} in pylopdf.{suffix}"
    if status == "planned":
        title = MILESTONES[str(milestone)]
        return f"pylopdf plans the capability of pymupdf's {name} in the {title} milestone of ROADMAP.md.{suffix}"
    if status == "integration":
        return f"pylopdf leaves pymupdf's {name} to an ecosystem tool.{suffix}"
    return f"pylopdf does not provide pymupdf's {name}.{suffix}"


def _removed_015(release: dict[str, object], public: set[str]) -> list[str]:
    """Return the names of pylopdf 0.15.0's public API that pylopdf no longer provides."""
    return sorted(set(cast("list[str]", release["symbols"])) - public)


def hints(manifest: dict[str, object], release: dict[str, object], public: set[str]) -> dict[str, str]:
    """Return every hint, checking that each removed 0.15 name has one and each replacement is public."""
    entries = manifest["entries"]
    if not isinstance(entries, dict):
        msg = "the manifest's entries must be an object"
        raise TypeError(msg)
    messages = {name: message for name in entries if (message := _message(name, entries[name])) is not None}
    replacements = cast("dict[str, dict[str, str]]", release["replacements"])
    problems = []
    for name, replacement in replacements.items():
        target = replacement["pylopdf"]
        if target not in public:
            problems.append(f"{name}: the replacement {target} is not in api/public-api.json")
        if name in messages:
            # A pymupdf name that pylopdf 0.15 also used, such as TextPage, keeps both hints.
            messages[name] += f" pylopdf 0.15's {name} is {target}. {replacement['hint']}"
        else:
            messages[name] = f"{name} is {target} in pylopdf. {replacement['hint']}"
    problems.extend(
        f"{name}: pylopdf 0.15 provided it; give it a hint in api/pylopdf-0.15.json"
        for name in _removed_015(release, public)
        if name not in messages
    )
    if problems:
        raise SystemExit("\n".join(problems))
    return messages


def _literal(text: str) -> str:
    """Render a string literal as ruff formats it: double quotes unless that needs more escapes."""
    if text.count('"') > text.count("'"):
        body = json.dumps(text, ensure_ascii=False)[1:-1].replace('\\"', '"').replace("'", "\\'")
        return "'" + body + "'"
    return json.dumps(text, ensure_ascii=False)


def render(manifest: dict[str, object], release: dict[str, object], public: set[str]) -> str:
    """Render the generated module."""
    messages = hints(manifest, release, public)
    lines = [HEADER]
    lines.extend(f"    {_literal(name)}: {_literal(messages[name])},\n" for name in sorted(messages))
    lines.append("}\n")
    lines.append("\n#: Names of pylopdf 0.15.0's public API that pylopdf no longer provides.\n")
    lines.append("PYLOPDF_015_REMOVED: frozenset[str] = frozenset(\n    {\n")
    lines.extend(f"        {json.dumps(name)},\n" for name in _removed_015(release, public))
    lines.append("    }\n)\n")
    entries = cast("dict[str, object]", manifest["entries"])
    replacements = cast("dict[str, object]", release["replacements"])
    lines.append("\n#: Hinted names that only pylopdf 0.15 had, which pymupdf programs cannot use.\n")
    lines.append("PYLOPDF_015_ONLY: frozenset[str] = frozenset(\n    {\n")
    lines.extend(f"        {json.dumps(name)},\n" for name in sorted(set(replacements) - set(entries)))
    lines.append("    }\n)\n")
    return "".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Write the hints module, or with ``--check`` report whether it is current."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail instead of writing stale output")
    args = parser.parse_args(argv)
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    release = json.loads(RELEASE_PATH.read_text(encoding="utf-8"))
    public = public_symbols(json.loads(PUBLIC_API_PATH.read_text(encoding="utf-8")))
    expected = render(manifest, release, public)
    current = HINTS_PATH.read_text(encoding="utf-8") if HINTS_PATH.exists() else ""
    if current == expected:
        return 0
    if args.check:
        sys.stderr.write(f"{HINTS_PATH.relative_to(ROOT)} is stale; run tools/generate_migration_hints.py\n")
        return 1
    HINTS_PATH.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
