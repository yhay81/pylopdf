"""Generate pylopdf's migration hints from the pymupdf capability map.

``src/pylopdf/_migration_hints.py`` maps every pymupdf name that pylopdf does
not provide under that name to one English message: the replacement and the
map's hint for a replaced name, the roadmap milestone for a planned
capability, and the hint or the fact that pylopdf leaves it out for the rest. AttributeError
messages and ``python -m pylopdf.migrate`` read it. The script also writes
the replaced-name map at the end of ``docs/en/llms.txt`` for coding
assistants. Run it after editing ``api/pymupdf-parity.json``; ``--check``
reports stale output without writing it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from check_parity import MILESTONES

ROOT = Path(__file__).resolve().parent.parent
MANIFEST_PATH = ROOT / "api" / "pymupdf-parity.json"
HINTS_PATH = ROOT / "src" / "pylopdf" / "_migration_hints.py"
LLMS_PATH = ROOT / "docs" / "en" / "llms.txt"
LLMS_MARKER = "pymupdf name map (generated from api/pymupdf-parity.json"

HEADER = '''"""Migration hints for pymupdf names that pylopdf does not provide.

Generated by ``tools/generate_migration_hints.py`` from
``api/pymupdf-parity.json``; do not edit by hand. Keys are pymupdf names: a
module attribute, ``Class.member``, or a prefix ending in ``*`` that covers a
group of module constants.
"""

HINTS: dict[str, str] = {
'''


def _message(name: str, entry: dict[str, object]) -> str | None:
    """Return the hint message for one manifest entry, or None when pylopdf provides the name."""
    status = entry["status"]
    relation = entry["relation"]
    target = entry["pylopdf"]
    milestone = entry["milestone"]
    hint = entry.get("hint")
    suffix = f" {hint}" if hint else ""
    if status == "available":
        if relation == "same" and target == name:
            return None
        return f"pymupdf's {name} is {target} in pylopdf.{suffix}"
    if status == "planned":
        title = MILESTONES[str(milestone)]
        return f"pylopdf plans the capability of pymupdf's {name} in the {title} milestone of ROADMAP.md.{suffix}"
    if status == "integration":
        return f"pylopdf leaves pymupdf's {name} to an ecosystem tool.{suffix}"
    return f"pylopdf does not provide pymupdf's {name}.{suffix}"


def render(manifest: dict[str, object]) -> str:
    """Render the generated module for a parsed manifest."""
    entries = manifest["entries"]
    if not isinstance(entries, dict):
        msg = "the manifest's entries must be an object"
        raise TypeError(msg)
    lines = [HEADER]
    for name in sorted(entries):
        message = _message(name, entries[name])
        if message is not None:
            lines.append(f"    {json.dumps(name)}: {json.dumps(message, ensure_ascii=False)},\n")
    lines.append("}\n")
    return "".join(lines)


def render_llms(manifest: dict[str, object], current: str) -> str:
    """Replace everything from the map's heading line in ``llms.txt`` with the current map."""
    entries = manifest["entries"]
    if not isinstance(entries, dict):
        msg = "the manifest's entries must be an object"
        raise TypeError(msg)
    head = current.split(LLMS_MARKER, 1)[0].rstrip("\n")
    lines = [
        head,
        "",
        f"{LLMS_MARKER}; each pymupdf name that pylopdf replaced, its",
        "replacement, and the migration hint):",
    ]
    for name in sorted(entries):
        entry = entries[name]
        if entry["status"] == "available" and entry["relation"] == "replaced":
            lines.append(f"- {name} -> {entry['pylopdf']}: {entry['hint']}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write the hints module and the llms.txt map, or with ``--check`` report whether they are current."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail instead of writing stale output")
    args = parser.parse_args(argv)
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    current_llms = LLMS_PATH.read_text(encoding="utf-8")
    outputs = {
        HINTS_PATH: render(manifest),
        LLMS_PATH: render_llms(manifest, current_llms),
    }
    stale = [
        path for path, text in outputs.items() if (path.read_text(encoding="utf-8") if path.exists() else "") != text
    ]
    if not stale:
        return 0
    if args.check:
        for path in stale:
            sys.stderr.write(f"{path.relative_to(ROOT)} is stale; run tools/generate_migration_hints.py\n")
        return 1
    for path in stale:
        path.write_text(outputs[path], encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
